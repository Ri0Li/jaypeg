from __future__ import annotations

import logging
import subprocess
from dataclasses import dataclass
from pathlib import Path

from src import __version__
from src.develop import full_develop
from src.formats import companion_jpg_path

log = logging.getLogger("jaypeg")


@dataclass
class ExtractResult:
    status: str  # ok | failed
    method: str | None  # preview | develop
    jpg_path: Path | None
    bytes_written: int | None
    reason: str | None


def _run_text(cmd: list[str], timeout: int = 120) -> subprocess.CompletedProcess[str]:
    if log.isEnabledFor(5):
        log.log(5, "exec: %s", " ".join(cmd))
    return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, check=False)


def _extract_tag_to_file(raw: Path, tag: str, dest: Path) -> bool:
    dest.parent.mkdir(parents=True, exist_ok=True)
    proc = subprocess.run(
        ["exiftool", "-b", f"-{tag}", str(raw)],
        capture_output=True,
        timeout=120,
        check=False,
    )
    if proc.returncode != 0 or not proc.stdout:
        return False
    dest.write_bytes(proc.stdout)
    return True


def _valid_jpeg(path: Path, min_bytes: int) -> bool:
    if not path.exists():
        return False
    size = path.stat().st_size
    if size < min_bytes:
        return False
    head = path.read_bytes()[:3]
    return head.startswith(b"\xff\xd8\xff")


def _apply_metadata(raw: Path, jpg: Path, tool_name: str) -> None:
    software = f"{tool_name}/{__version__}"
    cmd = [
        "exiftool",
        "-overwrite_original",
        "-TagsFromFile",
        str(raw),
        "-all:all",
        "--preview:all",
        f"-Software={software}",
        f"-ProcessingSoftware={software}",
        f"-XMP-xmp:CreatorTool={software}",
        f"-UserComment=Generated by {software} as RAW companion JPEG",
        # Pixels already upright after develop auto-orient; keep Orientation=1
        "-Orientation=1",
        "-n",
        str(jpg),
    ]
    proc = _run_text(cmd, timeout=180)
    if proc.returncode != 0:
        log.warning(
            "metadata copy warning: %s",
            proc.stderr.strip() or proc.stdout.strip(),
        )


def _finalize_jpg(raw: Path, tmp: Path, out: Path, *, tool_name: str) -> int:
    # No resize / recompress — keep native embed or full-res develop bytes.
    if not tmp.exists() or not tmp.read_bytes()[:3].startswith(b"\xff\xd8\xff"):
        raise RuntimeError("invalid jpeg before finalize")
    tmp.replace(out)
    _apply_metadata(raw, out, tool_name)
    return out.stat().st_size


def has_embedded_preview(raw: Path) -> bool:
    proc = _run_text(
        ["exiftool", "-s3", "-PreviewImage", "-JpgFromRaw", str(raw)],
        timeout=60,
    )
    if proc.returncode != 0:
        return False
    lines = [ln.strip() for ln in proc.stdout.splitlines() if ln.strip() and ln.strip() != "-"]
    return len(lines) > 0


def extract_companion(
    raw: Path,
    *,
    output_ext: str,
    min_jpeg_bytes: int,
    rewrite: bool,
    enable_gpu: bool,
    tool_name: str,
    write: bool,
    develop_fallback: bool = True,
    force_develop: bool = False,
) -> ExtractResult:
    out = companion_jpg_path(raw, output_ext)

    if out.exists() and out.stat().st_size > 0 and not rewrite:
        return ExtractResult(
            status="failed",
            method=None,
            jpg_path=out,
            bytes_written=None,
            reason="companion_exists_use_rewrite",
        )

    if not write:
        if force_develop:
            if develop_fallback:
                return ExtractResult("ok", "develop", out, None, "would_force_develop")
            return ExtractResult(
                "failed",
                None,
                out,
                None,
                "would_fail_force_develop_disabled",
            )
        if has_embedded_preview(raw):
            return ExtractResult("ok", "preview", out, None, "would_extract_preview")
        if develop_fallback:
            return ExtractResult("ok", "develop", out, None, "would_try_develop_fallback")
        return ExtractResult(
            "failed",
            None,
            out,
            None,
            "would_fail_no_preview_develop_disabled",
        )

    tmp = out.with_suffix(out.suffix + ".partial")
    if tmp.exists():
        tmp.unlink()

    preview_ok = False
    if not force_develop:
        for tag in ("PreviewImage", "JpgFromRaw"):
            try:
                if _extract_tag_to_file(raw, tag, tmp) and _valid_jpeg(tmp, min_jpeg_bytes):
                    preview_ok = True
                    log.debug("preview ok via %s for %s", tag, raw)
                    break
                if tmp.exists():
                    tmp.unlink()
            except Exception as exc:  # noqa: BLE001
                log.debug("preview %s failed for %s: %s", tag, raw, exc)
                if tmp.exists():
                    tmp.unlink(missing_ok=True)

        if preview_ok:
            try:
                size = _finalize_jpg(raw, tmp, out, tool_name=tool_name)
                return ExtractResult("ok", "preview", out, size, None)
            except Exception as exc:  # noqa: BLE001
                if tmp.exists():
                    tmp.unlink(missing_ok=True)
                if out.exists():
                    out.unlink(missing_ok=True)
                return ExtractResult("failed", "preview", None, None, f"postprocess_failed:{exc}")

    if not develop_fallback:
        log.warning(
            "%s for %s → develop disabled",
            "force_develop" if force_develop else "preview failed",
            raw,
        )
        return ExtractResult("failed", None, None, None, "develop_fallback_disabled")

    if force_develop:
        log.info("FORCE_DEVELOP → full-res develop for %s", raw)
    else:
        log.warning("preview failed for %s → trying full-res develop fallback", raw)

    try:
        full_develop(raw, tmp, enable_gpu=enable_gpu)
        if not _valid_jpeg(tmp, min_jpeg_bytes):
            if tmp.exists():
                tmp.unlink(missing_ok=True)
            return ExtractResult("failed", "develop", None, None, "develop_output_too_small")
        size = _finalize_jpg(raw, tmp, out, tool_name=tool_name)
        return ExtractResult("ok", "develop", out, size, None)
    except Exception as exc:  # noqa: BLE001
        if tmp.exists():
            tmp.unlink(missing_ok=True)
        return ExtractResult("failed", "develop", None, None, f"develop_failed:{exc}")
